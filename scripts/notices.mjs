// Generates THIRD_PARTY_NOTICES.md: the licenses of the crates and npm packages shipped in the app.
// Each distinct license text is printed once, with the list of packages that ship it.
import { execFileSync } from "node:child_process"
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"

const LICENSE_FILE = /^(licen[cs]e|copying|notice)/i

const licenseTexts = (dir) =>
  readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f))
    .sort()
    .map((f) => readFileSync(join(dir, f), "utf8").trim())

/** Crates linked into the app: normal dependencies reachable from pr-radar, every target OS. */
const crates = () => {
  const meta = JSON.parse(
    execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], {
      cwd: "src-tauri",
      maxBuffer: 1 << 28,
    }),
  )
  const byId = new Map(meta.packages.map((p) => [p.id, p]))
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]))
  const seen = new Set()
  const walk = (id) => {
    for (const d of nodes.get(id).deps)
      if (d.dep_kinds.some((k) => k.kind === null) && !seen.has(d.pkg)) {
        seen.add(d.pkg)
        walk(d.pkg)
      }
  }
  walk(meta.resolve.root)
  return [...seen].map((id) => {
    const p = byId.get(id)
    return {
      name: p.name,
      version: p.version,
      license: p.license ?? "see text",
      source: `https://crates.io/crates/${p.name}/${p.version}`,
      texts: licenseTexts(dirname(p.manifest_path)),
    }
  })
}

/** Production npm packages (the bundled frontend). */
const npmPackages = () =>
  JSON.parse(execFileSync("npm", ["query", ".prod"], { maxBuffer: 1 << 26 }))
    .filter((p) => !p.private)
    .map((p) => ({
      name: p.name,
      version: p.version,
      license: p.license ?? "see text",
      source: `https://www.npmjs.com/package/${p.name}/v/${p.version}`,
      texts: licenseTexts(p.path),
    }))

const pkgs = [...crates(), ...npmPackages()].sort(
  (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
)

const groups = new Map()
const bare = []
for (const p of pkgs) {
  if (!p.texts.length) bare.push(p)
  for (const text of p.texts) {
    const key = text.replace(/\s+/g, " ")
    const g = groups.get(key) ?? { text, list: [] }
    g.list.push(p)
    groups.set(key, g)
  }
}

const id = (p) => `${p.name} ${p.version} (${p.license})`
const out = [
  "# Third-party notices",
  "",
  "PR Radar includes the open source packages below. Generated by `npm run notices`, do not edit.",
  "",
  "Packages under the Mozilla Public License 2.0 are used unmodified; their source code is available at the link given for each one.",
  "",
  "## MPL-2.0 source code",
  "",
  ...pkgs
    .filter((p) => p.license.includes("MPL-2.0"))
    .map((p) => `- ${p.name} ${p.version}: ${p.source}`),
  "",
  "## License texts",
  "",
]
for (const { text, list } of groups.values()) {
  out.push(...list.map((p) => `- ${id(p)}`), "", "```", text, "```", "")
}
if (bare.length)
  out.push(
    "## Packages without a license file",
    "",
    "The license is the one declared in the package metadata; its standard text applies.",
    "",
    ...bare.map((p) => `- ${id(p)}: ${p.source}`),
    "",
  )

writeFileSync("THIRD_PARTY_NOTICES.md", out.join("\n"))
console.log(`THIRD_PARTY_NOTICES.md: ${pkgs.length} packages`)
